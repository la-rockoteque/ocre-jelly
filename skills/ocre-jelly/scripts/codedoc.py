C_FAMILY = {".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx", ".mts", ".cts", ".java", ".kt", ".kts", ".cs",
            ".go", ".rs", ".swift", ".php", ".c", ".h", ".cc", ".cpp", ".cxx", ".hpp", ".m", ".mm",
            ".scala", ".dart", ".groovy", ".fs"}
HASH_FAMILY = {".rb", ".sh", ".bash", ".zsh", ".pl", ".pm", ".r", ".yaml", ".yml", ".toml", ".ex", ".exs",
               ".tf", ".ps1", ".nim", ".cr"}
PYTHON = {".py", ".pyi"}
STRINGS = {".json", ".arb", ".po", ".pot", ".resx", ".properties", ".strings", ".xlf", ".xliff"}
PROSE = {".md", ".mdx", ".markdown", ".txt", ".rst", ".adoc"}  # scanned whole, like scan.py (used by --diff)

# One regex per resource format; group "v" is the user-facing text.
STRING_VALUE = {
    ".json": re.compile(r'"(?P<k>(?:\\.|[^"\\])*)"\s*:\s*"(?P<v>(?:\\.|[^"\\])*)"'),
    ".po": re.compile(r'^msgstr(?:\[\d+\])?\s+"(?P<v>(?:\\.|[^"\\])*)"', re.M),
    ".resx": re.compile(r"<value>(?P<v>[^<]*)</value>"),
    ".properties": re.compile(r"^\s*(?![#!])[^=:\s]+\s*[=:]\s*(?P<v>.+)$", re.M),
    ".strings": re.compile(r'"(?:\\.|[^"\\])*"\s*=\s*"(?P<v>(?:\\.|[^"\\])*)"\s*;'),
    ".xlf": re.compile(r"<target[^>]*>(?P<v>[^<]*)</target>"),
}
STRING_VALUE.update({".arb": STRING_VALUE[".json"], ".pot": STRING_VALUE[".po"], ".xliff": STRING_VALUE[".xlf"]})
PLACEHOLDER = re.compile(r"\{\{[^}]*\}\}|\{[\w.,\s]*\}|%(?:\d+\$)?[sdif@]|\$t\([^)]*\)|<[^>]+>|\\[nt]")
LOCALE_IN_PATH = re.compile(r"(?:^|[\\/._-])([a-z]{2})(?:[-_]([A-Z]{2}|[a-z]{2}))?(?=[\\/._-]|$)")

C_TOKEN = re.compile(
    r'(?P<str>"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])*\'|`(?:\\.|[^`\\])*`)'
    r"|(?P<block>/\*.*?\*/)|(?P<line>//[^\n]*)",
    re.S,
)
# ponytail: Rust lifetimes ('a) and C# verbatim strings (@"") can confuse the string match; rare in doc lines
HASH_TOKEN = re.compile(r'(?P<str>"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])*\')|(?P<line>#[^\n]*)')

FILLER = set("""a an the of to for this that given specified current new instance method function class
property value object gets get sets set or and returns return is by with from in on it its be
constructor ctor default main""".split())

TAG_WITH_NAME = r"(?:param|arg|argument|prop|property|typeparam|template|tparam|throws|exception|raises|field)"


@dataclass
class Block:
    start: int          # 1-based line of the first comment line
    lines: list[str]    # comment text with comment markers stripped, one per source line
    doc: bool           # a doc comment (/** */, ///, docstring, Go/Ruby leading comments)
    decl: str           # the declaration line it documents, "" if unknown


def split_ident(text: str) -> set[str]:
    words = re.findall(r"[A-Z]+(?=[A-Z][a-z]|\d|\b)|[A-Z]?[a-z]+|\d+", text)
    return {stem(w.lower()) for w in words}


ABBREV = {"identifier": "id", "number": "num", "string": "str", "index": "idx", "configuration": "config",
          "cfg": "config", "message": "msg", "error": "err", "context": "ctx", "request": "req",
          "response": "res", "argument": "arg", "parameter": "param", "value": "val", "length": "len",
          "directory": "dir", "information": "info", "button": "btn", "source": "src",
          "destination": "dst", "callback": "cb", "count": "cnt", "temporary": "tmp", "character": "char"}


def stem(word: str) -> str:
    word = word[:-1] if len(word) > 3 and word.endswith("s") and not word.endswith("ss") else word
    return ABBREV.get(word, word)


def strip_markers(raw: str) -> list[str]:
    out = []
    for line in raw.split("\n"):
        line = re.sub(r"^\s*(?:/\*\*!?|/\*!?|\*/|\*(?!/)|///?!?|//|#+'?|\"\"\"|''')", "", line, count=1)
        out.append(re.sub(r"\*/\s*$", "", line).rstrip())
    return out


def next_decl(lines: list[str], after: int) -> str:
    """First code line after a comment, skipping blanks, annotations and attributes."""
    for line in lines[after:after + 8]:
        s = line.strip()
        if s and not re.match(r"^(?:@|\[|#\[|//|/\*|\*|#)", s):
            return s
    return ""


def c_blocks(src: str, ext: str) -> list[Block]:
    lines = src.split("\n")
    blocks: list[Block] = []
    for m in C_TOKEN.finditer(src):
        if m.lastgroup == "str":
            continue
        start = src.count("\n", 0, m.start()) + 1
        raw = m.group()
        end = start + raw.count("\n")
        if m.lastgroup == "block":
            doc = raw.startswith(("/**", "/*!")) and raw != "/**/"
            blocks.append(Block(start, strip_markers(raw), doc, next_decl(lines, end)))
            continue
        doc = raw.startswith(("///", "//!")) or ext == ".go"
        prev = blocks[-1] if blocks else None
        own_line = lines[start - 1].lstrip().startswith("//")
        if prev and own_line and prev.start + len(prev.lines) == start and prev.doc == doc and not prev.lines[0].startswith("/*"):
            prev.lines += strip_markers(raw)  # merge consecutive // lines into one block
            prev.decl = next_decl(lines, start)
        else:
            blocks.append(Block(start, strip_markers(raw), doc and own_line, next_decl(lines, start)))
    return blocks


def hash_blocks(src: str) -> list[Block]:
    lines = src.split("\n")
    blocks: list[Block] = []
    for m in HASH_TOKEN.finditer(src):
        if m.lastgroup == "str" or m.group().startswith("#!"):
            continue
        start = src.count("\n", 0, m.start()) + 1
        own_line = lines[start - 1].lstrip().startswith("#")
        prev = blocks[-1] if blocks else None
        if prev and own_line and prev.start + len(prev.lines) == start:
            prev.lines += strip_markers(m.group())
            prev.decl = next_decl(lines, start)
        else:
            blocks.append(Block(start, strip_markers(m.group()), own_line, next_decl(lines, start)))
    return blocks


def py_blocks(src: str) -> list[Block]:
    lines = src.split("\n")
    blocks: list[Block] = []
    prev_type = tokenize.NEWLINE
    try:
        tokens = list(tokenize.generate_tokens(io.StringIO(src).readline))
    except (tokenize.TokenError, SyntaxError, IndentationError):
        return hash_blocks(src)  # unparseable: fall back to plain # comments
    for tok in tokens:
        if tok.type == tokenize.COMMENT:
            start = tok.start[0]
            prev = blocks[-1] if blocks else None
            if prev and not prev.doc and prev.start + len(prev.lines) == start:
                prev.lines += strip_markers(tok.string)
            else:
                blocks.append(Block(start, strip_markers(tok.string), False, ""))
        elif (tok.type == tokenize.STRING and prev_type in (tokenize.NEWLINE, tokenize.INDENT, tokenize.DEDENT, tokenize.NL, tokenize.ENCODING)
              and re.match(r"^[rRuU]?(\"\"\"|''')", tok.string)):
            body = re.sub(r"^[rRuU]?(\"\"\"|''')|(\"\"\"|''')$", "", tok.string)
            decl = next((lines[i].strip() for i in range(tok.start[0] - 2, max(tok.start[0] - 22, -1), -1)
                         if re.match(r"^\s*(?:async\s+def|def|class)\s", lines[i])), "")
            blocks.append(Block(tok.start[0], body.split("\n"), True, decl))
        if tok.type not in (tokenize.COMMENT, tokenize.NL):
            prev_type = tok.type
    return blocks


def strings_prose(src: str, ext: str) -> list[str]:
    """User-facing text of a resource file, on its own line numbers; keys and placeholders masked."""
    prose = [""] * (src.count("\n") + 1)
    for m in STRING_VALUE[ext].finditer(src):
        if m.groupdict().get("k", "").startswith("@"):
            continue  # .arb metadata
        line = src.count("\n", 0, m.start("v"))
        text = PLACEHOLDER.sub(" ", m.group("v"))
        prose[line] = (prose[line] + " " + text).strip()
    return prose


def locale_from_path(path: str, known: list[str]) -> list[str] | None:
    """fr-CA/nav.json, messages.fr.resx, fr.lproj -> the matching locale tag, if we ship one."""
    for m in LOCALE_IN_PATH.finditer(path):
        lang, region = m.group(1), m.group(2)
        tag = f"{lang}-{region.upper()}" if region else lang
        if tag in known:
            return [tag]
        if lang in known:
            return [lang]
    return None


def blocks_for(src: str, ext: str) -> list[Block]:
    if ext in PYTHON:
        return py_blocks(src)
    if ext in HASH_FAMILY:
        return hash_blocks(src)
    return c_blocks(src, ext)


# ---- masking doc syntax ------------------------------------------------------

def mask_doc(text: str) -> str:
    """Blank out doc syntax so only prose reaches the prose checks. Keeps newlines."""
    blank = lambda m: re.sub(r"[^\n]", " ", m.group())  # noqa: E731
    rules = [
        (r"<code>.*?</code>|<example>.*?</example>|```.*?```", re.S),
        (r"(?m)^\s*@example\b[^@]*", re.S),                         # JSDoc example bodies
        (r"(?m)^\s*(?:>>>|\.\.\.)\s.*$", 0),                           # doctest
        (r"\{@\w+[^}]*\}", 0),                                          # {@link Foo}
        (rf"@{TAG_WITH_NAME}\b\s*(?:\{{[^}}]*\}}\s*)?[\w.$\[\]=]*\s*-?", re.I),
        (r"@\w+\s*(?:\{[^}]*\})?(?:\s*\[[^\]]*\])?", 0),                 # other tags, types, YARD [Type]
        (r"(?m)^\s*-\s*(?:Parameters?(?:\s+\w+)?|Returns|Throws|Note|Warning|Precondition|Complexity)\s*:", 0),  # Swift
        (r"<(?:see|seealso|paramref|typeparamref|inheritdoc|autogeneratedoc)\b[^>]*/?>", 0),
        (r"</?\w+(?:\s+\w+=\"[^\"]*\")*\s*/?>", 0),                    # remaining XML tags
        (r"(?m):(?:param|type|raises|var|ivar|cvar)\s+[^:]*:|:r?type:|:returns?:", 0),
        (r"(?m)^\s*(?:Args|Arguments|Parameters|Returns|Yields|Raises|Examples?|Attributes|Notes?|See Also|Throws|Errors|Panics|Safety)\s*:?\s*$", 0),
        (r"(?m)^\s*-{3,}\s*$", 0),                                      # numpy underlines
        (r"(?m)^\s*\*?\w+\*?\s*(?:\([^)]*\))?\s*:(?=\s)", 0),           # Google "name (type):"
        (r"(?m)^\s*#\s*(?:Examples?|Errors|Panics|Safety|Arguments|Returns)\s*$", 0),  # rustdoc sections
    ]
    for pat, flags in rules:
        text = re.sub(pat, blank, text, flags=flags)
    return text


def first_sentence(text: str) -> str:
    flat = " ".join(text.split())
    return re.split(r"(?<=[.!?])\s", flat, maxsplit=1)[0] if flat else ""


def echoes(description: str, ident_words: set[str]) -> bool:
    words = [stem(w.lower()) for w in re.findall(r"[A-Za-z]+", description)]
    content = [w for w in words if w not in FILLER_STEMS]
    return bool(words) and all(w in ident_words for w in content)


FILLER_STEMS = {stem(w) for w in FILLER}


# ---- doc checks --------------------------------------------------------------

PARAM_LINE = re.compile(
    rf"@{TAG_WITH_NAME}\s+(?:\{{[^}}]*\}}\s*)?\[?(\w+)[^\s]*\s*-?\s*(.*)"   # @param {T} name - desc
    r"|<param\s+name=\"(\w+)\">(.*?)</param>"                             # .NET
    r"|:param\s+(?:\w+\s+)?(\w+):\s*(.*)"                                 # reST
    r"|-\s*Parameter\s+(\w+):\s*(.*)"                                       # Swift
    r"|^\s*(\w+)\s*(?:\([^)]*\))?:\s+(.+)",                               # Google style
    re.I,
)
RETURNS_ECHO = re.compile(
    r"(?:@returns?\s*(?:\{[^}]*\}\s*)?|<returns>\s*|:returns?:\s*|^\s*Returns:\s*)"
    r"(?:the\s+)?(?:result|return value|value|returned value|output)\.?\s*(?:</returns>)?\s*$",
    re.I | re.M,
)
GENERATED = re.compile(
    r"<autogeneratedoc\s*/>|TODO:?\s*Edit XML Comment Template"          # GhostDoc
    r"|\b_(?:summary|extended_summary|description|type)_\b"               # autoDocstring
    r"|@param\s+\{\*\}"                                                  # Document This
    r"|^\s*@(?:param|arg)\s+[\w$]+\s*$|^\s*@returns?\s*$",                # empty IDE stub tags
    re.I | re.M,
)
THIS_METHOD = re.compile(
    r"\bthis (?:method|function|class|property|constructor|module|component|hook)\s+"
    r"(?:is used to|will|is responsible for|allows you to|helps(?: to)?|is designed to|serves to)\b"
    r"|\ban? (?:helper|utility|simple) (?:function|method|class) (?:that|to|for|which)\b",
    re.I,
)


def doc_hits(b: Block) -> list[dict]:
    hits = []
    raw = "\n".join(b.lines)

    def hit(offset_line: int, sev: str, cat: str, match: str) -> None:
        hits.append({"line": b.start + offset_line, "severity": sev, "category": cat, "match": match.strip()[:80]})

    for i, line in enumerate(b.lines):
        for rx, sev, cat in ((GENERATED, "hard", "generated-doc"), (THIS_METHOD, "soft", "this-method")):
            for m in rx.finditer(line):
                hit(i, sev, cat, m.group())
        if b.doc and RETURNS_ECHO.search(line):
            hit(i, "hard", "returns-echo", line)
        m = PARAM_LINE.search(line) if b.doc else None
        if m:
            name, desc = next((m.group(k), m.group(k + 1)) for k in (1, 3, 5, 7, 9) if m.group(k))
            if desc and echoes(re.sub(r"</?\w+[^>]*>", " ", desc), split_ident(name)):
                hit(i, "hard", "param-echo", line)
    if b.doc and b.decl:
        summary = first_sentence(mask_doc(raw))
        if summary and echoes(summary, split_ident(b.decl)):
            hit(0, "hard", "echo-doc", f"{summary} <- {b.decl[:40]}")
            hits[-1]["span"] = [b.start, b.start + len(b.lines) - 1]  # the whole block, for --diff
    return hits


REGISTER = None  # set from the config in main()
LENGTH_KEEP = 3  # per file; long comment sentences are common, so show the worst and count the rest


def cap_length(hits: list[dict]) -> list[dict]:
    longs = [h for h in hits if h["category"] == "ste-length"]
    if len(longs) <= LENGTH_KEEP:
        return hits
    words = lambda h: int(h["match"].split()[0])  # noqa: E731
    keep = sorted(longs, key=words, reverse=True)[:LENGTH_KEEP]
    rest = len(longs) - LENGTH_KEEP
    summary = {"line": keep[0]["line"], "severity": "soft", "category": "ste-length",
               "match": f"{rest} more sentences over 25 words in this file (--all lists them)"}
    return [h for h in hits if h["category"] != "ste-length"] + keep + [summary]


def fold_aliases(hits: list[dict]) -> list[dict]:
    """One glossary-alias line per alias and file, with a count, instead of one per use."""
    seen: dict[str, dict] = {}
    out = []
    for h in sorted(hits, key=lambda h: h["line"]):
        if h["category"] != "glossary-alias":
            out.append(h)
            continue
        key = h["match"].lower()
        if key in seen:
            seen[key]["count"] = seen[key].get("count", 1) + 1
        else:
            seen[key] = dict(h)
            out.append(seen[key])
    for h in seen.values():
        if h.get("count", 1) > 1:
            h["match"] += f" (x{h['count']}, first at L{h['line']})"
    return out


def condense(hits: list[dict]) -> list[dict]:
    return fold_aliases(cap_length(hits))


def gitlab_report(results: list[dict]) -> list[dict]:
    """GitLab Code Quality (Code Climate) issues: shown in the merge request widget."""
    import hashlib
    out, seen = [], collections.Counter()
    for h in results:
        base = f"{h['file']}|{h['category']}|{h['match']}"
        seen[base] += 1  # the same text twice in one file needs two fingerprints
        key = f"{base}|{seen[base]}".encode()
        out.append({
            "description": f"{h['category']}: {h['match']}",
            "check_name": f"ocre-jelly/{h['category']}",
            "fingerprint": hashlib.sha1(key).hexdigest(),  # line left out, so moving text keeps its identity
            "severity": "major" if h["severity"] == "hard" else "minor",
            "location": {"path": h["file"], "lines": {"begin": h["line"]}},
        })
    return out


def parse_diff(diff: str) -> dict[str, set[int]]:
    """Added line numbers per file, from a unified diff (git diff, git show, a PR's .diff)."""
    added: dict[str, set[int]] = {}
    path, line = None, 0
    for raw in diff.split("\n"):
        if raw.startswith("+++ "):
            name = raw[4:].split("\t")[0].strip().strip('"')
            path = None if name == "/dev/null" else (name[2:] if name[:2] in ("b/", "w/", "i/") else name)
            if path is not None:
                added.setdefault(path, set())
        elif raw.startswith("@@"):
            m = re.match(r"@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@", raw)
            line = int(m.group(1)) if m else 0
        elif path is None or raw.startswith(("--- ", "diff ", "index ", "\\")):
            continue
        elif raw.startswith("+"):
            added[path].add(line)
            line += 1
        elif raw.startswith(" ") or raw == "":
            line += 1
    return {p: lines for p, lines in added.items() if lines}


def scan_source(src: str, ext: str, aliases: dict[str, list[str]] | None = None, all_hits: bool = False,
                locales: list[str] | None = None, protected_terms: list[str] | None = None) -> list[dict]:
    ctx = "docs" if ext in PROSE else "strings" if ext in STRINGS else "comments"
    if ext in PROSE:
        hits = scan.scan(src, aliases=aliases, locales=locales, protected_terms=protected_terms, register=REGISTER, context=ctx)
        return sorted(hits if all_hits else condense(hits), key=lambda h: (h["line"], h["severity"]))
    if ext in STRINGS:  # each string is its own paragraph, so scan values one by one
        hits = []
        for n, value in enumerate(strings_prose(src, ext)):
            if value:
                hits += [{**h, "line": n + 1}
                         for h in scan.scan(value, aliases=aliases, locales=locales, protected_terms=protected_terms, register=REGISTER, context=ctx)]
        return sorted(hits if all_hits else condense(hits), key=lambda h: (h["line"], h["severity"]))
    blocks = blocks_for(src, ext)
    total = src.count("\n") + 1
    prose = [""] * total
    for b in blocks:
        masked = mask_doc("\n".join(b.lines)).split("\n")
        for i, text in enumerate(masked):
            if b.start - 1 + i < total:
                prose[b.start - 1 + i] = text
    hits = scan.scan("\n".join(prose), aliases=aliases, locales=locales, protected_terms=protected_terms, register=REGISTER, context=ctx)
    for b in blocks:
        hits += doc_hits(b)
    hits = scan.suppress(hits, src)  # markers in the raw source also cover doc-comment findings
    if not all_hits:
        hits = condense(hits)
    return sorted(hits, key=lambda h: (h["line"], h["severity"]))


# ---- code-unchanged check ----------------------------------------------------

def code_only(src: str, ext: str) -> str:
    """Source with every comment and docstring removed and whitespace collapsed."""
    if ext in PYTHON:
        try:
            out, prev = [], tokenize.NEWLINE
            for tok in tokenize.generate_tokens(io.StringIO(src).readline):
                is_doc = (tok.type == tokenize.STRING and prev in (tokenize.NEWLINE, tokenize.INDENT, tokenize.DEDENT, tokenize.NL)
                          and re.match(r"^[rRuU]?(\"\"\"|''')", tok.string))
                if tok.type not in (tokenize.COMMENT, tokenize.NL, tokenize.INDENT, tokenize.DEDENT) and not is_doc:
                    out.append(tok.string)
                if tok.type not in (tokenize.COMMENT, tokenize.NL):
                    prev = tok.type
            return " ".join(" ".join(out).split())
        except (tokenize.TokenError, SyntaxError, IndentationError):
            pass
    rx = HASH_TOKEN if ext in HASH_FAMILY else C_TOKEN
    stripped = rx.sub(lambda m: m.group() if m.lastgroup == "str" else " ", src)
    return " ".join(stripped.split())


COMMENT_START = re.compile(r"^\s*(?:$|//|/\*|\*|#|\"\"\"|''')")
TRIPLE = re.compile(r"^[rRuU]?(\"\"\"|''')")


def docstring_lines(src: str) -> set[int]:
    """0-based line numbers covered by Python docstrings (tokenize is exact here)."""
    lines, prev = set(), tokenize.NEWLINE
    try:
        for tok in tokenize.generate_tokens(io.StringIO(src).readline):
            if (tok.type == tokenize.STRING and TRIPLE.match(tok.string)
                    and prev in (tokenize.NEWLINE, tokenize.INDENT, tokenize.DEDENT, tokenize.NL)):
                lines.update(range(tok.start[0] - 1, tok.end[0]))
            if tok.type not in (tokenize.COMMENT, tokenize.NL):
                prev = tok.type
    except (tokenize.TokenError, SyntaxError, IndentationError):
        pass
    return lines


def code_prefix(line: str) -> str | None:
    """Code before a trailing comment, or None when the line has no comment marker."""
    m = re.search(r"\s(?://|#)", line)
    return line[:m.start()].rstrip() if m else None


def changed_code_lines(a: str, b: str, ext: str) -> str | None:
    """Independent line-level check: every changed line must be a comment, blank,
    or keep its code before a trailing comment. It doesn't trust the tokenizer,
    so a regex literal like /[/*]/ can't hide a code change from it."""
    la, lb = a.split("\n"), b.split("\n")
    doc_a, doc_b = (docstring_lines(a), docstring_lines(b)) if ext in PYTHON else (set(), set())
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, la, lb, autojunk=False).get_opcodes():
        if tag == "equal":
            continue
        bad_a = [i for i in range(i1, i2) if i not in doc_a and not COMMENT_START.match(la[i])]
        bad_b = [j for j in range(j1, j2) if j not in doc_b and not COMMENT_START.match(lb[j])]
        if not bad_a and not bad_b:
            continue
        if len(bad_a) == len(bad_b) and all(
                code_prefix(la[i]) is not None and code_prefix(la[i]) == code_prefix(lb[j])
                for i, j in zip(bad_a, bad_b)):
            continue  # only trailing comments changed
        i = bad_a[0] if bad_a else None
        text = la[i] if i is not None else lb[bad_b[0]]
        where = f"line {i + 1}" if i is not None else f"new line {bad_b[0] + 1}"
        return f"code changed at {where}: {text.strip()[:60]!r}"
    return None


def same_code(a: str, b: str, ext: str) -> str | None:
    """None only when both checks agree that only comments changed."""
    ca, cb = code_only(a, ext), code_only(b, ext)
    if ca != cb:
        i = next((k for k, (x, y) in enumerate(zip(ca, cb)) if x != y), min(len(ca), len(cb)))
        return f"code changed near: {ca[max(0, i - 30):i + 30]!r} -> {cb[max(0, i - 30):i + 30]!r}"
    return changed_code_lines(a, b, ext)


