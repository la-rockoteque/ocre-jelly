def selftest() -> None:
    cs = '''/// <summary>
/// Gets the name of the user.
/// </summary>
/// <param name="userId">The user identifier.</param>
/// <returns>The result.</returns>
/// <autogeneratedoc />
// TODO Edit XML Comment Template for GetUserName
public string GetUserName(int userId) => "";

/// <summary>Retries the call three times, then throws, so callers see one failure.</summary>
public void CallWithRetry() {}
'''
    cats = {h["category"] for h in scan_source(cs, ".cs")}
    assert {"echo-doc", "param-echo", "returns-echo", "generated-doc"} <= cats, cats
    assert not [h for h in scan_source(cs, ".cs") if h["line"] >= 10], "good doc flagged"

    ts = '''/**
 * This function is used to delve into the cache.
 * @param {string} key - The key.
 * @returns {number} Seconds until the entry expires, or -1 when it is missing.
 * @example
 * ttl("a") // Here's the thing
 */
export function ttl(key: string): number { const url = "http://x.io//not-a-comment"; return 0 }
'''
    hits = scan_source(ts, ".ts")
    cats = {h["category"] for h in hits}
    assert {"this-method", "ai-vocabulary", "param-echo"} <= cats, cats
    assert "throat-clearing" not in cats, "example code was scanned"
    assert "returns-echo" not in cats

    py = '''def get_user(user_id):
    """Get the user.

    Args:
        user_id (int): The user id.

    >>> get_user(1)  # let's dive in
    """
    return None  # A helper function that fetches it
'''
    cats = {h["category"] for h in scan_source(py, ".py")}
    assert {"echo-doc", "param-echo", "this-method"} <= cats, cats
    assert "throat-clearing" not in cats

    stubs = '"""_summary_\n\n    Args:\n        x (_type_): _description_\n    """'
    assert "generated-doc" in {h["category"] for h in scan_source("def f(x):\n    " + stubs + "\n    return x\n", ".py")}
    assert "generated-doc" in {h["category"] for h in scan_source("/**\n * @param {*} a\n * @returns\n */\nfunction f(a) {}\n", ".js")}
    swift = "/// Loads the cache from disk.\n/// - Parameter path: The path.\nfunc load(path: String) {}\n"
    assert "param-echo" in {h["category"] for h in scan_source(swift, ".swift")}, scan_source(swift, ".swift")

    wordy = "".join(f"// {' '.join(['w'] * (30 + k))}.\nint v{k};\n" for k in range(6))
    capped = [h for h in scan_source(wordy, ".c") if h["category"] == "ste-length"]
    assert len(capped) == 4 and sum("3 more" in h["match"] for h in capped) == 1, capped
    assert len([h for h in scan_source(wordy, ".c", all_hits=True) if h["category"] == "ste-length"]) == 6

    fr_json = '{\n  "title": "Il est important de noter que {{count}} e-mails partent",\n  "ok": "Enregistrer"\n}\n'
    hits = scan_source(fr_json, ".json", locales=["fr-CA"])
    assert {(h["line"], h["category"]) for h in hits} >= {(2, "throat-clearing"), (2, "locale-term")}, hits
    assert not [h for h in hits if "count" in h["match"]], "placeholder scanned"
    assert locale_from_path("src/i18n/locales/fr-CA/nav.json", ["en", "fr", "fr-CA"]) == ["fr-CA"]
    assert locale_from_path("Resources/Strings.fr.resx", ["en", "fr", "fr-CA"]) == ["fr"]
    assert locale_from_path("src/components/Button.json", ["en", "fr"]) is None
    po = 'msgid "Save"\nmsgstr "Plongeons dans la sauvegarde"\n'
    assert "throat-clearing" in {h["category"] for h in scan_source(po, ".po", locales=["fr"])}

    folded = fold_aliases([{"line": n, "severity": "soft", "category": "glossary-alias", "match": "ligne -> Item"} for n in (4, 9, 2)])
    assert len(folded) == 1 and folded[0]["match"] == "ligne -> Item (x3, first at L2)", folded

    diff = (
        "diff --git a/docs/a.md b/docs/a.md\n--- a/docs/a.md\n+++ b/docs/a.md\n@@ -1,3 +1,4 @@\n"
        " keep\n-old line\n+Here's the thing: new\n+second new\n unchanged\n\\ No newline at end of file\n"
        "diff --git a/gone.md b/gone.md\n--- a/gone.md\n+++ /dev/null\n@@ -1 +0,0 @@\n-bye\n"
        "diff --git a/n.ts b/n.ts\nnew file mode 100644\n--- /dev/null\n+++ b/n.ts\n@@ -0,0 +1,2 @@\n+// x\n+const y = 1\n"
        "diff --git a/old.md b/new name.md\nrename from old.md\n--- a/old.md\n+++ \"b/new name.md\"\n@@ -5,2 +7,3 @@\n ctx\n+added\n ctx\n"
    )
    assert parse_diff(diff) == {"docs/a.md": {2, 3}, "n.ts": {1, 2}, "new name.md": {8}}, parse_diff(diff)
    md = "Clean line.\nHere's the thing: added.\nLet's dive in, old text.\n"
    block = [h for h in scan_source("/**\n * Gets the user.\n * More.\n */\nfunction getUser() {}\n", ".ts") if h["category"] == "echo-doc"]
    assert block and block[0]["span"] == [1, 4], block
    kept = [h for h in scan_source(md, ".md", all_hits=True) if h["line"] in {2}]
    assert [h["category"] for h in kept] == ["throat-clearing"], kept

    quiet = "// ocre-jelly: ignore echo-doc\n/** Gets the user. */\nfunction getUser() {}\n"
    assert not [h for h in scan_source(quiet, ".ts") if h["category"] == "echo-doc"], "suppression ignored in code"

    rep_ = gitlab_report([{"file": "docs/a.md", "line": 3, "severity": "hard", "category": "throat-clearing", "match": "x"}])
    assert rep_[0]["severity"] == "major" and rep_[0]["location"] == {"path": "docs/a.md", "lines": {"begin": 3}}
    assert rep_[0]["check_name"] == "ocre-jelly/throat-clearing" and len(rep_[0]["fingerprint"]) == 40
    twice = gitlab_report([{"file": "a.md", "line": n, "severity": "soft", "category": "em-dash", "match": "x"} for n in (1, 9)])
    assert twice[0]["fingerprint"] != twice[1]["fingerprint"], "duplicate fingerprints"

    go = "// Parse parses.\nfunc Parse() {}\n"
    assert [h["category"] for h in scan_source(go, ".go")] == ["echo-doc"]

    assert same_code(ts, ts.replace("This function is used to delve into", "Reads"), ".ts") is None
    assert same_code(ts, ts.replace("return 0", "return 1"), ".ts")
    assert same_code(py, py.replace("Get the user.", "Load one user by id."), ".py") is None
    tricky = "const pattern = /[/*]/;\nfunction f() {\n  return 1\n}\n/* trailing */\n"
    assert same_code(tricky, tricky.replace("return 1", "return 999999"), ".ts"), "regex literal hid a code change"
    assert same_code(tricky, tricky.replace("trailing", "why it trails"), ".ts") is None
    inline = "x = compute()  # slow path\n"
    assert same_code(inline, inline.replace("slow path", "cached after first call"), ".py") is None
    assert same_code(inline, inline.replace("compute()", "compute(1)"), ".py")
    multi = "/**\n * Old summary.\n */\nint f();\n"
    assert same_code(multi, multi.replace(" * Old summary.", " * New summary.\n * With a second line."), ".c") is None
    assert same_code(py, py.replace("return None", "return 1"), ".py")
    print("selftest ok")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("files", nargs="*")
    ap.add_argument("--lang", help="extension for stdin input, e.g. .ts")
    ap.add_argument("--glossary", metavar="MD")
    ap.add_argument("--locale", help="comma list, e.g. en-CA,fr-CA; a locale in a resource file's path wins")
    ap.add_argument("--no-config", action="store_true", help="ignore the layered ocre-jelly JSON config")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--format", choices=("text", "json", "gitlab"), default=None,
                    help="gitlab: a Code Quality report for the merge request widget")
    ap.add_argument("--fail-on", choices=("hard", "soft"), help="exit 1 when a finding of this severity or higher remains")
    ap.add_argument("--all", action="store_true", help="list every long sentence and every alias use, not a summary")
    ap.add_argument("--same-code", nargs=2, metavar=("ORIGINAL", "REWRITTEN"))
    ap.add_argument("--diff", action="store_true",
                    help="read a unified diff on stdin; report only findings on added lines (prose files included)")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()

    if args.selftest:
        return selftest()
    if args.same_code:
        a, b = (Path(p) for p in args.same_code)
        problem = same_code(a.read_text(encoding="utf-8"), b.read_text(encoding="utf-8"), a.suffix.lower())
        if not args.no_config:
            import telemetry
            telemetry.record("gate", gate="same-code", ok=problem is None, ext={a.suffix.lower() or "(none)": 1})
        print(problem or "code unchanged")
        sys.exit(1 if problem else 0)

    global LENGTH_KEEP, REGISTER
    cfg = scan.load_settings(args.no_config)
    REGISTER = cfg.get("register")
    if not args.no_config:
        LENGTH_KEEP = cfg["thresholds"]["length_hits_per_file"]
    aliases = {}
    glossary = args.glossary or scan.default_glossary(cfg)
    if glossary:
        with open(glossary, encoding="utf-8") as f:
            aliases = scan.load_glossary(scan.read_capped(f))
    files = args.files
    only: dict[str, set[int]] = {}  # --diff: file -> added lines
    if args.diff:
        root = Path(cfg.get("_root") or Path.cwd())
        supported = C_FAMILY | HASH_FAMILY | PYTHON | STRINGS | PROSE
        for rel, lines in parse_diff(scan.read_capped(sys.stdin)).items():
            full = root / rel
            if Path(rel).suffix.lower() in supported and full.is_file() and root.resolve() in full.resolve().parents:
                only[str(full)] = lines
        files = args.files = list(only)
        if not files:
            return print("-- no added lines in supported files")
    if cfg.get("_root") and cfg.get("ignore_paths"):
        import config
        files = [f for f in files if not config.ignored(f, Path(cfg["_root"]), cfg["ignore_paths"])]
        if len(files) < len(args.files):
            print(f"-- skipped {len(args.files) - len(files)} file(s) matching ignore_paths", file=sys.stderr)
    started = time.perf_counter()
    sources = [(p, Path(p).suffix.lower()) for p in files] or [("<stdin>", (args.lang or ".js").lower())]
    results = []
    for name, ext in sources:
        if name == "<stdin>":
            src = scan.read_capped(sys.stdin)
        else:
            with open(name, encoding="utf-8") as f:
                src = scan.read_capped(f)
        locales = scan.parse_locales(args.locale) or cfg["locales"] or None
        if ext in STRINGS:
            locales = locale_from_path(name, scan.available_locales()) or locales
        if name in only:  # scan the whole file for context, keep what the diff added
            lines = only[name]
            hits = [h for h in scan_source(src, ext, aliases, True, locales, cfg["protected_terms"])
                    if h["line"] in lines or ("span" in h and any(h["span"][0] <= n <= h["span"][1] for n in lines))]
            hits = hits if args.all else condense(hits)
            name = str(Path(name).relative_to(Path(cfg.get("_root") or Path.cwd())))
        else:
            hits = scan_source(src, ext, aliases, args.all, locales, cfg["protected_terms"])
        results += [{**h, "file": name} for h in hits]
    if cfg["severity"]:
        import config
        results = config.apply_severity(results, cfg["severity"])
    if not args.no_config:
        import telemetry
        telemetry.record("codedoc", started, results, locales=cfg["locales"] or None,
                         ext=telemetry.extensions([n if n != "<stdin>" else f"x{e}" for n, e in sources]),
                         files=len(sources), skipped=len(args.files) - len(files))
    fmt = args.format or ("json" if args.json else "text")
    failing = {"hard": {"hard"}, "soft": {"hard", "soft"}}.get(args.fail_on or "", set())
    code = 1 if any(h["severity"] in failing for h in results) else 0
    if fmt == "gitlab":
        print(json.dumps(gitlab_report(results), indent=2, ensure_ascii=False))
        sys.exit(code)
    if fmt == "json":
        print(json.dumps(results, indent=2))
        sys.exit(code)
    multi = len(sources) > 1
    for h in results:
        where = f"{h['file']}:L{h['line']}" if multi else f"L{h['line']}"
        print(f"{where:<6} {h['severity']:<4} {h['category']:<22} {h['match']!r}")
    hard = sum(h["severity"] == "hard" for h in results)
    print(f"-- {len(results)} candidates ({hard} hard). Candidates only; confirm in context.")
    sys.exit(code)


if __name__ == "__main__":
    try:
        main()
    except ValueError as e:  # bad locale tag or glossary: a clear message, not a traceback
        scan._record_error(e)
        sys.exit(f"{Path(__file__).name}: {e}")
    except Exception as e:
        scan._record_error(e)
        raise
