#!/usr/bin/env python3
"""Scan the prose inside code comments and doc comments.

Handles JSDoc/TSDoc, Javadoc, KDoc, .NET XML docs, Doxygen, PHPDoc, rustdoc,
Go doc comments, Swift markup (C-family comments), Python docstrings and `#`
comments (tokenize), and `#` comments for Ruby/YARD, shell, YAML, Perl, R.

It masks the doc syntax (tags, types, parameter names, XML elements, code
examples, doctests), runs the prose checks from scan.py on what is left, and
adds doc-comment checks:
  echo-doc        the summary only restates the declaration ("Gets the user name." on GetUserName)
  param-echo      a parameter description only restates its name ("@param id The id.")
  returns-echo    "@returns The result."
  generated-doc   GhostDoc-style placeholders (<autogeneratedoc />, "TODO Edit XML Comment Template")
  this-method     "This method is used to...", "A helper function that..."

Usage:
  codedoc.py FILE [FILE ...] [--glossary MD] [--json]
  codedoc.py --lang .ts < source
  codedoc.py --same-code ORIGINAL REWRITTEN     exit 1 if anything but comments changed
  codedoc.py --selftest

Security posture: stdlib only, no network, no subprocess. Reads only the files it is given.
"""
